// Writes supabase/seed.sql from src/data/demoSeed.ts.  Run: npx tsx scripts/generate-seed.ts
// The seed goes through the same database rules (lock, resolve, publish) as the app.
import { writeFileSync } from 'node:fs';
import { DEMO_SEASON, demoEvents, demoIds, demoPlayers, demoTeams } from '../src/data/demoSeed';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const num = (n: number | null | undefined) => (n == null ? 'null' : String(n));
const holes = (h: (number | null)[]) => `array[${h.map((x) => (x == null ? 'null' : x)).join(',')}]::smallint[]`;

export function seedSql(): string {
  const out: string[] = [];
  out.push(`-- JIMULATOR demo season. Generated by scripts/generate-seed.ts — do not edit by hand.
-- Event 1: eight players split Mon Nov 2 / Tue Nov 3, official results published.
-- Event 2: Day 1 complete, Day 2 pending (scores private).
-- Event 3: 2-person team scramble with the season teams, two teams per day.
-- Event 4: 2-person best ball with stroke indexes, groups set (draft).
-- Replace the placeholder handicap indexes with current GHIN indexes before real play.
begin;
select set_config('jimulator.workflow', 'on', true);

insert into public.league_settings (id, league_name, season_year, field_size_basis)
values (1, 'JIMULATOR Golf Simulator League', ${DEMO_SEASON}, 'starters')
on conflict (id) do update set season_year = excluded.season_year;
`);
  out.push('insert into public.players (id, name, ghin_number, handicap_index, handicap_source, active) values');
  out.push(
    demoPlayers
      .map((p) => `  (${q(p.id)}, ${q(p.name)}, null, ${num(p.handicap_index)}, ${q(p.handicap_source)}, true)`)
      .join(',\n') + '\non conflict (id) do nothing;\n',
  );
  out.push('insert into public.events (id, season_year, event_number, name, format, team_size, counting_scores, match_type, hole_si, course_name, tees, par9, course_rating9, slope9, sim_settings) values');
  out.push(
    demoEvents
      .map((e) => {
        const s = e.setup;
        const simJson = JSON.stringify(s?.sim_settings ?? { green_speed: '', fairway_firmness: '', wind: '', putting: '', mulligans: '' });
        const si = e.hole_si ? `array[${e.hole_si.join(',')}]::smallint[]` : 'null';
        return `  (${q(demoIds.eid(e.n))}, ${DEMO_SEASON}, ${e.n}, ${q(e.name)}, ${q(e.format ?? 'individual')}, ${e.team_size ?? 2}, ${e.counting_scores ?? 1}, ${q(e.match_type ?? 'singles')}, ${si}, ${q(s?.course_name ?? '')}, ${q(s?.tees ?? '')}, ${num(s?.par9)}, ${num(s?.course_rating9)}, ${num(s?.slope9)}, ${q(simJson)}::jsonb)`;
      })
      .join(',\n') + '\non conflict (id) do nothing;\n',
  );
  out.push('insert into public.teams (id, season_year, name, player_a, player_b) values');
  out.push(
    demoTeams
      .map((t) => `  (${q(demoIds.tid(t.n))}, ${DEMO_SEASON}, ${q(t.name)}, ${q(demoIds.pid(t.a))}, ${q(demoIds.pid(t.b))})`)
      .join(',\n') + '\non conflict (id) do nothing;\n',
  );
  // Rule checks for the seed run through the normal triggers: turn the workflow bypass off.
  out.push(`select set_config('jimulator.workflow', 'off', true);\n`);
  for (const e of demoEvents) {
    const ev = q(demoIds.eid(e.n));
    for (const s of e.sessions) {
      out.push(`insert into public.event_sessions (event_id, session_number, session_date, start_time) values (${ev}, ${s.day}, ${q(s.date)}, ${q(s.time)});`);
      for (const p of s.players) {
        out.push(
          `insert into public.session_assignments (event_id, session_id, player_id) select ${ev}, id, ${q(demoIds.pid(p))} from public.event_sessions where event_id = ${ev} and session_number = ${s.day};`,
        );
      }
    }
    if (e.lock) out.push(`select app_private.lock_event_core(${ev});\nselect set_config('jimulator.workflow', 'off', true);`);
    for (const [p, sc] of Object.entries(e.scores ?? {})) {
      out.push(
        `update public.round_scores r set hole_scores = ${holes(sc.holes)}, status = ${q(sc.status)} from public.session_assignments a where a.id = r.assignment_id and a.event_id = ${ev} and a.player_id = ${q(demoIds.pid(Number(p)))};`,
      );
    }
    for (const d of e.resolveDays ?? []) {
      out.push(`select app_private.resolve_session_core(id) from public.event_sessions where event_id = ${ev} and session_number = ${d};\nselect set_config('jimulator.workflow', 'off', true);`);
    }
    if (e.publish) out.push(`select app_private.publish_event_core(${ev});\nselect set_config('jimulator.workflow', 'off', true);`);
    out.push('');
  }
  out.push('commit;\n');
  return out.join('\n');
}

if (process.argv[1]?.endsWith('generate-seed.ts')) {
  writeFileSync(new URL('../supabase/seed.sql', import.meta.url), seedSql());
  console.log('wrote supabase/seed.sql');
}
